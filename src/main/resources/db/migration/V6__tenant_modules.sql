CREATE TABLE public.tenant_modules (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id bigint NOT NULL REFERENCES public.tenants (id),
    module character varying(50) NOT NULL,
    created_at timestamp without time zone DEFAULT now() NOT NULL,
    created_by bigint,
    CONSTRAINT uq_tenant_module UNIQUE (tenant_id, module)
);

INSERT INTO public.tenant_modules (tenant_id, module)
SELECT t.id, m.module
  FROM public.tenants t
 CROSS JOIN (VALUES ('TRIAGE'), ('CONSULTATION'), ('BILLING'), ('PATIENT_PORTAL'), ('REPORTS')) AS m (module);
